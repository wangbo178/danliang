import assert from 'node:assert/strict'
import {applyForecastBulk, buildTmallForecastRows, priceRecords, orderRecords, forecastNumber} from '../frontend/src/utils/tmallForecast.mjs'
const channel = '货架-常规', dates = ['2026-11-01', '2026-11-02', '2026-11-03']
const records = dates.map(period => ({channel, kind: 'day', period, amount: 10000}))
let values = {aov: {[channel]: {}}, orders: {[channel]: {}}}
const rows = () => buildTmallForecastRows(records, [channel], priceRecords(values), orderRecords(values))
const apply = (metric, operation, text, days = dates) => applyForecastBulk(values, rows(), {channels: [channel], metric, dates: days, operation, text})
values = apply('aov', 'set', '100')
assert.deepEqual(Object.values(values.aov[channel]), [100,100,100])
assert.equal(rows()[2].values[dates[0]].amount, 100)
values = apply('aov', 'add', '0.10', dates.slice(1))
assert.deepEqual(Object.values(values.aov[channel]), [100,100.1,100.1])
values = apply('aov', 'subtract', '0.10', dates.slice(1))
assert.deepEqual(Object.values(values.aov[channel]), [100,100,100])
values = apply('orders', 'add', '20')
assert.deepEqual(Object.values(values.orders[channel]), [120,120,120])
values = apply('aov', 'set', '200')
assert.equal(rows()[2].values[dates[0]].amount, 120) // 手填单量不随客单价变动。
values = apply('orders', 'clear', '')
assert.equal(rows()[2].values[dates[0]].amount, 50)
values = apply('orders', 'paste', '2,597\n0\t—')
assert.deepEqual(Object.values(values.orders[channel]), [2597,0,null])
assert.equal(rows()[2].values[dates[1]].amount, 0)
const before = JSON.stringify(values)
assert.throws(() => apply('orders', 'subtract', '1'), /未修改任何数据/)
assert.equal(JSON.stringify(values), before)
assert.throws(() => apply('orders', 'paste', '1 2 3 4'))
assert.throws(() => apply('aov', 'subtract', '300'))
assert.throws(() => apply('aov', 'set', '0'))
values = apply('aov', 'clear', '')
values = apply('orders', 'clear', '')
assert.throws(() => apply('orders', 'add', '10'), /没有原值/)
assert.equal(forecastNumber('2,597.50', 'aov'), 2597.5)
assert.ok(Number.isNaN(forecastNumber('1.5', 'orders')))
console.log('区间设值、粘贴、加减、千位小数、手填覆盖、恢复自动、负数整批拒绝和缺失基数验证通过')
